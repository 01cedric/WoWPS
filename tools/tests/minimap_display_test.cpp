namespace wowee::rendering {
struct Camera { glm::vec3 forward{0,1,0}; glm::vec3 getForward() const { return forward; } };
struct Minimap {
    bool enabled = true, hasCachedFrame = true, haveRect_ = true;
    bool rotateWithCamera = false, squareShape = false;
    float rectX_ = 0, rectY_ = 0, rectW_ = 140, rectH_ = 140;
    float viewRadius = 400, opacity_ = 1;
    int mapSize = 200;
    VkPipeline displayPipeline = reinterpret_cast<VkPipeline>(1);
    VkPipelineLayout displayPipelineLayout = VK_NULL_HANDLE;
    VkDescriptorSet displayDescSet = VK_NULL_HANDLE;
    VkBuffer quadVB = VK_NULL_HANDLE;
    void render(VkCommandBuffer, const Camera&, const glm::vec3&, int, int,
                VkExtent2D, float = 0, bool = false);
};

// Generated by the runner from src/rendering/minimap.cpp: both the push
// constant declaration and the whole function, with no copied rendering logic.
#include "minimap_render_source.inc"
} // namespace wowee::rendering

int main() {
    using namespace wowee::rendering;
    Minimap map; Camera camera;
    const int sizes[][2] = {{1280,720}, {1920,1080}, {1024,768}, {3440,1440}, {1280,720}};
    for (const auto& size : sizes) for (const int divisor : {1, 2}) {
        const auto width = size[0], height = size[1];
        const float uiScale = height / 768.0f;
        map.rectW_ = map.rectH_ = 140 * uiScale;
        map.rectX_ = width - map.rectW_ - 16 * uiScale;
        map.rectY_ = 24 * uiScale;
        const VkExtent2D extent{static_cast<uint32_t>(width / divisor), static_cast<uint32_t>(height / divisor)};
        recorded = {};
        map.render(VK_NULL_HANDLE, camera, {0, 0, 0}, width, height, extent);
        require(recorded.draws == 1, "valid display records one draw");
        closeTo(recorded.viewport.x, 0, "viewport starts at the framebuffer left");
        closeTo(recorded.viewport.y, 0, "viewport starts at the framebuffer top");
        closeTo(recorded.viewport.width, extent.width, "viewport uses actual target width");
        closeTo(recorded.viewport.height, extent.height, "viewport uses actual target height");
        closeTo(recorded.viewport.minDepth, 0, "viewport resets minimum depth");
        closeTo(recorded.viewport.maxDepth, 1, "viewport resets maximum depth");
        require(recorded.scissor.offset.x == 0 && recorded.scissor.offset.y == 0 &&
                recorded.scissor.extent.width == extent.width && recorded.scissor.extent.height == extent.height,
                "scissor covers the actual display target");
        require(recorded.push.size() == sizeof(MinimapDisplayPush), "records complete minimap push constants");
        MinimapDisplayPush push;
        std::memcpy(&push, recorded.push.data(), sizeof(push));
        closeTo(push.rect.x * extent.width, map.rectX_ / divisor, "map x stays aligned with the authored UI rectangle");
        closeTo(push.rect.y * extent.height, map.rectY_ / divisor, "map y stays aligned with the authored UI rectangle");
        closeTo(push.rect.z * extent.width, map.rectW_ / divisor, "map width follows display scaling");
        closeTo(push.rect.w * extent.height, map.rectH_ / divisor, "map height follows display scaling");
    }
    const int invalid[][4] = {{0,720,1280,720}, {1280,0,1280,720}, {1280,720,0,720}, {1280,720,1280,0}};
    for (const auto& values : invalid) {
        recorded = {};
        map.render(VK_NULL_HANDLE, camera, {0,0,0}, values[0], values[1],
                   {static_cast<uint32_t>(values[2]), static_cast<uint32_t>(values[3])});
        require(recorded.pipelineCalls == 0 && recorded.draws == 0 && recorded.push.empty(),
                "zero window or framebuffer dimension records no draw commands");
    }
    std::puts("PASS minimap: production render resets dynamic viewport/scissor, preserves UI rect at four resolutions and half-size targets, ignores zero dimensions");
    const Minimap good=map;
    const float nan=std::numeric_limits<float>::quiet_NaN(),inf=std::numeric_limits<float>::infinity();
    const auto reject=[&](const glm::vec3& pos=glm::vec3(0),float orientation=0,bool hasOrientation=false){
        recorded={};map.render(VK_NULL_HANDLE,camera,pos,1280,720,{1280,720},orientation,hasOrientation);
        require(recorded.pipelineCalls==0 && recorded.draws==0 && recorded.push.empty(),"invalid state emits no GPU commands");
    };
    for(float bad:{nan,inf,-inf}) {
        map=good;map.rectX_=bad;reject();map=good;map.rectY_=bad;reject();
        map=good;map.rectW_=bad;reject();map=good;map.rectH_=bad;reject();
        map=good;map.viewRadius=bad;reject();map=good;map.opacity_=bad;reject();
        map=good;reject({bad,0,0});reject({0,bad,0});reject({0,0,0},bad,true);
        camera.forward={bad,1,0};reject();camera.forward={0,1,0};
    }
    map=good;map.rectW_=0;reject();map=good;map.rectH_=-1;reject();
    map=good;map.haveRect_=false;map.mapSize=0;reject();map=good;map.viewRadius=0;reject();
    map=good;reject({1e30f,0,0});
    std::puts("PASS minimap invalid data: hidden/invalid rectangles, world conversion bounds, radius, opacity and orientation skip GPU recording");
    for(float opacity:{-2.f,2.f}) {
        map=good;map.opacity_=opacity;recorded={};
        map.render(VK_NULL_HANDLE,camera,{0,0,0},1280,720,{1280,720});
        require(recorded.draws==1,"finite out-of-range opacity still draws");
        MinimapDisplayPush push;std::memcpy(&push,recorded.push.data(),sizeof(push));
        closeTo(push.opacity,opacity<0?0.f:1.f,"opacity is bounded");
    }
    std::puts("PASS minimap opacity: finite values clamped to the display range");

}
